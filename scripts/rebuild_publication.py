"""Rebuild the v1.1.0 publication's simulation evidence and derived figures.

This explicit command replaces the current root evidence bundle. The historical
publication remains available at Git tag v1.0.1 and its existing DOI. Importing
this module performs no experiments and writes no files.
"""
import argparse
from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.1.0"
PUBLICATION_DATE = "2026-11-09"
SOURCE_DATE_EPOCH = int(datetime(2026, 11, 9, tzinfo=timezone.utc).timestamp())
EVALUATION_CONFIG = {"subdivisions": 2, "n_packets": 2000, "seed": 42,
                     "bandwidth_policy": "equal_total"}
SWEEP_CONFIG = {"n_packets": 500, "seeds": [7, 19, 42, 73, 101]}
CAPACITY_CONFIG = {"arithmetic_intensity_flops_per_byte": 4.0}
MANIFEST_PATH = Path("artifacts/publication_manifest.json")
FIGURE_NAMES = ("fig1_hop_cdf", "fig2_latency_cdf", "fig3_latency_load",
                "fig4_tail_ratio", "fig5_allreduce", "fig6_balanced_cut",
                "fig7_hotspot", "fig8_energy_proxy")
RETIRED_FIGURES = tuple(
    "figures/" + name + "." + extension
    for name in ("fig6_bisection", "fig8_energy", "fig9_workload", "fig10_power")
    for extension in ("png", "pdf"))
OUTPUT_PATHS = frozenset(
    ["artifacts/results.json", "artifacts/performance_model.json",
     "examples/results/design_sweep.json", "paper/generated_results.tex"]
    + ["figures/" + name + "." + extension
       for name in FIGURE_NAMES for extension in ("png", "pdf")])


def _sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _source_hashes():
    paths = sorted((ROOT / "sim").glob("*.py"))
    paths.extend([ROOT / "requirements.txt", Path(__file__).resolve()])
    return {path.relative_to(ROOT).as_posix(): _sha256(path) for path in paths}


def _write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n", encoding="utf-8")


def _number(value, places=3):
    return f"{value:.{places}f}".rstrip("0").rstrip(".")


def _tex_macro(name, value):
    return "\\newcommand{\\" + name + "}{" + str(value) + "}"


def generated_results(evaluation, capacity, sweep):
    """Generate only values/row bodies; paper source supplies table captions."""
    lines = ["% Generated by scripts/rebuild_publication.py. Do not edit by hand.",
             "% Exploratory simulation and unvalidated capacity assumptions are distinct.",
             _tex_macro("PublicationVersion", VERSION),
             _tex_macro("PublicationDate", PUBLICATION_DATE),
             _tex_macro("EvaluationPacketCount", evaluation["config"]["n_packets"]),
             _tex_macro("EvaluationSeed", evaluation["config"]["seed"]),
             _tex_macro("EvaluationRankCount", evaluation["candidates"][0]["resource_budget"]["nodes"]),
             _tex_macro("EvaluationPayloadBytes", evaluation["candidates"][0]["all_reduce"]["per_rank_payload_flits"] * 64)]
    evaluation_rows, collective_rows = [], []
    names = {"sphere": ("Sphere", "Sphere"),
             "sphere_chords": ("ChordSphere", "Sphere+chords"),
             "torus": ("Torus", "Torus")}
    for candidate in evaluation["candidates"]:
        prefix, label = names[candidate["name"]]
        latency = candidate["uncontended_latency"]
        stats, budget = candidate["topology_stats"], candidate["resource_budget"]
        tail = latency["p99_latency_ns"] / latency["p50_latency_ns"]
        values = {
            "IsolatedPfiftyNs": latency["p50_latency_ns"],
            "IsolatedPninetyNineNs": latency["p99_latency_ns"],
            "IsolatedTailRatio": tail,
            "AverageHops": stats["avg_hops"],
            "MaxHops": stats["max_hops"],
            "TreeAllReduceUs": candidate["all_reduce"]["tree_time_ns"] / 1000,
            "RingAllReduceUs": candidate["all_reduce"]["ring_time_ns"] / 1000,
            "CutGbps": candidate["balanced_coordinate_cut"]["cut_bandwidth_gbps"],
            "LinkGbps": budget["link_bandwidth_gbps_per_direction"],
            "AggregateBandwidthGbps": budget["aggregate_directed_bandwidth_gbps"],
            "WireLengthMm": budget["total_link_length_mm"],
        }
        for suffix, value in values.items():
            lines.append(_tex_macro(prefix + suffix, _number(value)))
        evaluation_rows.append(" & ".join([label, _number(stats["avg_hops"]),
            str(stats["max_hops"]), _number(latency["p50_latency_ns"]),
            _number(latency["p99_latency_ns"]), _number(tail)]) + r" \\")
        collective_rows.append(" & ".join([label, _number(values["RingAllReduceUs"]),
            _number(values["TreeAllReduceUs"]), _number(values["CutGbps"])]) + r" \\")
    aggregate = capacity["aggregate_bounds"]
    capacity_values = {
        "AssumedDenseFpEightPflops": aggregate["fp8_pflops_dense"],
        "AssumedHbmCapacityGb": aggregate["hbm_capacity_gb"],
        "LocalHbmTbps": aggregate["hbm_bw_TBps"],
        "RemoteHbmTbps": aggregate["effective_remote_hbm_bw_TBps"],
        "PartialPowerWatts": aggregate["power_component_subtotal_w"],
        "MinimumLocalPercent": 100 * (1 - aggregate["effective_remote_hbm_bw_TBps"] / aggregate["hbm_bw_TBps"]),
    }
    for name, value in capacity_values.items():
        lines.append(_tex_macro(name, _number(value)))
    capacity_rows = [
        r"Assumed dense FP8 peak (PFLOPS) & \AssumedDenseFpEightPflops \\",
        r"Assumed HBM capacity (GB) & \AssumedHbmCapacityGb \\",
        r"Assumed summed local HBM bandwidth (TB/s) & \LocalHbmTbps \\",
        r"Remote HBM endpoint ceiling (TB/s) & \RemoteHbmTbps \\",
        r"Necessary local-byte fraction (\%) & \MinimumLocalPercent \\",
        r"Partial component power assumption (W) & \PartialPowerWatts \\",
        r"Full-system power/efficiency & Not established \\",
    ]
    sweep_rows = []
    for cohort in sweep["cohorts"]:
        workload = "MoE" if cohort["workload"] == "moe_dispatch" else "Stencil"
        count = "FortyTwo" if cohort["rank_count"] == 42 else "OneSixtyTwo"
        policy = "EqualTotal" if cohort["bandwidth_policy"] == "equal_total" else "PerLink"
        prefix = ("Moe" if workload == "MoE" else "Stencil") + count + policy
        baseline = cohort["baseline"]
        ratio = baseline["paired_sphere_over_torus_p99_ratio"]
        for suffix, value in (("Ratio", ratio["median"]), ("RatioMin", ratio["min"]),
                              ("RatioMax", ratio["max"]),
                              ("SpherePninetyNineNs", baseline["sphere_p99_latency_ns"]["median"]),
                              ("TorusPninetyNineNs", baseline["torus_p99_latency_ns"]["median"])):
            lines.append(_tex_macro(prefix + suffix, _number(value)))
        sweep_rows.append(" & ".join([workload, str(cohort["rank_count"]),
            "equal total" if policy == "EqualTotal" else "per link",
            _number(baseline["sphere_p99_latency_ns"]["median"]),
            _number(baseline["torus_p99_latency_ns"]["median"]),
            _number(ratio["median"]), _number(ratio["min"]), _number(ratio["max"])]) + r" \\")
    for name, rows in (("EvaluationSummaryRows", evaluation_rows),
                       ("CollectiveSummaryRows", collective_rows),
                       ("SweepSummaryRows", sweep_rows),
                       ("CapacitySummaryRows", capacity_rows)):
        lines.append(_tex_macro(name, "\n" + "\n".join(rows) + "\n"))
    return "\n".join(lines) + "\n"


@contextmanager
def _build_environment():
    before_path = list(sys.path)
    previous_epoch = os.environ.get("SOURCE_DATE_EPOCH")
    sys.path.insert(0, str(ROOT))
    os.environ["SOURCE_DATE_EPOCH"] = str(SOURCE_DATE_EPOCH)
    try:
        yield
    finally:
        sys.path[:] = before_path
        if previous_epoch is None:
            os.environ.pop("SOURCE_DATE_EPOCH", None)
        else:
            os.environ["SOURCE_DATE_EPOCH"] = previous_epoch


def build_publication(output_root=ROOT):
    """Build in staging; publish only after source hashes remain unchanged."""
    output_root = Path(output_root).resolve()
    sources_before = _source_hashes()
    with _build_environment():
        import matplotlib
        import numpy as np
        from sim.performance_model import SPHERE_162, compute_aggregate, estimate_roofline
        from sim.run_evaluation import evaluate, write_figures
        from sim.run_sweep import run_sweep

        with tempfile.TemporaryDirectory(prefix="sphere-publication-") as temporary:
            staging = Path(temporary)
            evaluation, plots = evaluate(**EVALUATION_CONFIG)
            _write_json(staging / "artifacts/results.json", evaluation)
            write_figures(evaluation, plots, staging)
            aggregate = compute_aggregate(SPHERE_162)
            capacity = {
                "schema_version": 2,
                "design_assumptions": SPHERE_162,
                "aggregate_bounds": aggregate,
                "illustrative_remote_memory_roofline": estimate_roofline(
                    {"compute_tflops_by_precision": {"fp8": aggregate["fp8_pflops_dense"] * 1000},
                     "memory_bandwidth_TBps": aggregate["effective_remote_hbm_bw_TBps"]},
                    {"precision": "fp8", "arithmetic_intensity_flops_per_byte":
                     CAPACITY_CONFIG["arithmetic_intensity_flops_per_byte"]}),
                "limitations": [
                    "No measured performance, thermal or packaging validation.",
                    "Local stack bandwidth is not uniform remotely accessible bandwidth.",
                    "Six ports per tile is optimistic before memory-tile placement.",
                    "Remote bound can fall further with cuts, contention and failures.",
                    "No full-system power, efficiency ranking or competitor comparison.",
                ],
            }
            _write_json(staging / "artifacts/performance_model.json", capacity)
            sweep = run_sweep(**SWEEP_CONFIG)
            _write_json(staging / "examples/results/design_sweep.json", sweep)
            generated = staging / "paper/generated_results.tex"
            generated.parent.mkdir(parents=True, exist_ok=True)
            generated.write_text(generated_results(evaluation, capacity, sweep), encoding="utf-8")
            sources_after = _source_hashes()
            if sources_before != sources_after:
                raise ValueError("source files changed during generation; retry after edits finish")
            paths = sorted(path for path in staging.rglob("*") if path.is_file())
            manifest = {
                "schema_version": 1,
                "publication": {"version": VERSION, "date": PUBLICATION_DATE,
                                "evidence": "exploratory simulation plus explicitly unvalidated analytical assumptions"},
                "configuration": {"evaluation": EVALUATION_CONFIG, "sweep": SWEEP_CONFIG,
                                  "capacity": CAPACITY_CONFIG},
                "environment": {"python_version": platform.python_version(),
                                "numpy_version": np.__version__,
                                "matplotlib_version": matplotlib.__version__,
                                "source_date_epoch": SOURCE_DATE_EPOCH},
                "source_sha256": sources_after,
                "output_sha256": {path.relative_to(staging).as_posix(): _sha256(path) for path in paths},
                "retired_figure_paths": list(RETIRED_FIGURES),
                "rebuild_command": "python scripts/rebuild_publication.py",
                "reproducibility": "Source hashes identify exact input bytes, including uncommitted changes; no Git commit is asserted. JSON and figure bytes are reproducible in the recorded numerical/plotting environment. PDF creation metadata uses the fixed publication date.",
                "scope": "This manifest covers generated simulation artifacts, plots and LaTeX result macros; it does not claim to hash the separately authored paper PDF or validate hardware.",
            }
            # A manifest cannot contain its own output hash.
            _write_json(staging / MANIFEST_PATH, manifest)
            paths.append(staging / MANIFEST_PATH)
            output_root.mkdir(parents=True, exist_ok=True)
            for path in paths:
                destination = output_root / path.relative_to(staging)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, destination)
            for relative in RETIRED_FIGURES:
                stale = output_root / relative
                if stale.exists():
                    stale.unlink()
            return manifest


def check_publication(output_root=ROOT):
    """Validate existing source/output hashes without modifying any file."""
    output_root = Path(output_root).resolve()
    manifest = json.loads((output_root / MANIFEST_PATH).read_text(encoding="utf-8"))
    if manifest.get("schema_version") != 1:
        raise ValueError("unsupported publication manifest schema")
    publication = manifest.get("publication", {})
    if publication.get("version") != VERSION or publication.get("date") != PUBLICATION_DATE:
        raise ValueError("publication version/date does not match this builder")
    if manifest.get("configuration") != {"evaluation": EVALUATION_CONFIG,
            "sweep": SWEEP_CONFIG, "capacity": CAPACITY_CONFIG}:
        raise ValueError("publication configuration does not match this builder")
    if set(manifest.get("output_sha256", {})) != OUTPUT_PATHS:
        raise ValueError("publication manifest must list every expected output exactly once")
    if manifest.get("retired_figure_paths") != list(RETIRED_FIGURES):
        raise ValueError("publication retired-figure list does not match this builder")
    if manifest.get("source_sha256") != _source_hashes():
        raise ValueError("publication source hashes are stale; rebuild artifacts")
    for relative, expected in manifest["output_sha256"].items():
        path = (output_root / relative).resolve()
        if not path.is_relative_to(output_root) or not path.is_file() or _sha256(path) != expected:
            raise ValueError("missing or stale publication output: " + relative)
    if any((output_root / relative).exists() for relative in manifest["retired_figure_paths"]):
        raise ValueError("unsupported legacy figures remain in current output")
    return manifest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, default=ROOT,
                        help="output bundle root; default: this repository")
    parser.add_argument("--check", action="store_true",
                        help="validate committed hashes without rebuilding or writing files")
    args = parser.parse_args(argv)
    try:
        manifest = check_publication(args.output_root) if args.check else build_publication(args.output_root)
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    action = "Verified" if args.check else "Rebuilt"
    print(f"{action} publication v{manifest['publication']['version']}: "
          f"{len(manifest['output_sha256'])} generated evidence files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
